/** Mega-menu groups. Lahore & Others = anything outside Islamabad/Rawalpindi. */
export const menuGroups = [
  { id: 'isb', cities: ['Islamabad', 'Rawalpindi'] },
  { id: 'others', cities: ['Lahore', 'Gujar Khan', 'Wah', 'Murree', 'Other'] },
] as const;

/** Top-level projects per menu group, each with its nested sub-projects (Capital Smart City). */
export function projectTree() {
  return menuGroups.map((g) => ({
    ...g,
    items: projects
      .filter((p) => !p.parent && (g.cities as readonly string[]).includes(p.city))
      .map((p) => ({ project: p, children: projects.filter((c) => c.parent === p.id) })),
  }));
}

export function projectById(id: string): ProjectCard | undefined {
  return projects.find((p) => p.id === id);
}
